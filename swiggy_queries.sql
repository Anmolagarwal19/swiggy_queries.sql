#Display all customers who live in 'Delhi'.
SELECT 
    name, city
FROM
    customers
WHERE
    city = 'delhi';
    
#Find the average rating of all restaurants in 'Mumbai'.
SELECT city,
       ROUND(AVG(rating), 2) AS average_rating
FROM Restaurants
where city = 'mumbai'
GROUP BY city;

#List all customers who have placed at least one order.
SELECT DISTINCT
    c.customer_id, c.name
FROM
    customers c
        JOIN
    orders o
on
    c.customer_id = o.customer_id;
    
#Display the total number of orders placed by each customer.

SELECT 
    c.name, COUNT(o.order_id) AS total_orders
FROM
    customers c
        JOIN
    orders o USING (customer_id)
GROUP BY c.name;

#Find the total revenue generated by each restaurant.
SELECT 
    r.name,
    SUM(o.total_amount) AS total_revenue
FROM restaurants r
JOIN orders o
ON r.restaurant_id = o.restaurant_id
GROUP BY r.name;

#Find the top 5 restaurants with the highest average rating.
select name, avg(rating) from
restaurants
group by name
order by avg(rating) desc 
limit 5;

#Display all customers who have never placed an order.
SELECT 
    c.customer_id,
    c.name
FROM customers c
LEFT JOIN orders o
ON c.customer_id = o.customer_id
WHERE o.customer_id IS NULL;

#Find the number of orders placed by each customer in 'Mumbai'.
select c.customer_id, c.name, city, count(o.order_id)
from customers c join orders o
using(customer_id)
where city = 'mumbai'         
group by c.customer_id, c.name, city;

#Display all orders placed in the last 30 days.
select order_id, order_date from orders
where order_date >= (select date_sub(max(order_date), interval 30 day));

#List all delivery partners who have completed more than 1 delivery
SELECT
    dp.partner_id,
    dp.name,
    COUNT(distinct od.order_delivery_id) AS total_delivery
FROM DeliveryPartners dp
JOIN OrderDelivery od
ON dp.partner_id = od.partner_id
JOIN DeliveryUpdates du
ON od.order_id = du.order_id
WHERE du.status = 'Delivered'
GROUP BY dp.partner_id, dp.name
HAVING COUNT( distinct od.order_delivery_id) > 1;

#Find the customers who have placed orders on exactly three different days.
select c.customer_id, c.name, count(distinct o.order_date) as order_days
from customers c join orders o
using(customer_id)
group by c.customer_id, c.name
having count(distinct o.order_date) = 3;

#Find the delivery partner who has worked with the most different customers
SELECT 
    dp.partner_id,
    dp.name,
    COUNT(DISTINCT o.customer_id) AS no_of_customers
FROM deliverypartners dp
JOIN orderdelivery od
USING(partner_id)
JOIN orders o
USING(order_id)
GROUP BY dp.partner_id, dp.name
ORDER BY no_of_customers DESC
LIMIT 1;

#Identify customers who have the same city and have placed orders at the same restaurants, but on different dates.
SELECT DISTINCT
    c1.customer_id,
    c1.name,o1.order_date,
    c2.customer_id, o1.restaurant_id,
    c2.name,o2.order_date,
    o2.restaurant_id
FROM customers c1
JOIN orders o1
USING(customer_id)

JOIN customers c2
ON c1.city = c2.city
AND c1.customer_id < c2.customer_id

JOIN orders o2
ON c2.customer_id = o2.customer_id
AND o1.restaurant_id = o2.restaurant_id
AND o1.order_date <> o2.order_date;








